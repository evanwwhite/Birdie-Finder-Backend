import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
globalThis.window = {};
const legacy = require('../../birdie_finder_web/assets/legacy-import.js');
const raw = readFileSync(new URL('../fixtures/legacy/web-rounds.json',import.meta.url),'utf8');
const parsed = legacy.parseWebRounds(raw);
assert.equal(parsed.records.length,3);
assert.deepEqual(parsed.invalid,[]);
const match = slug => Promise.resolve(slug === 'synthetic-pine-loop' ? '11111111-1111-4111-8111-111111111111' : null);
const a = await legacy.previewWebLegacy(raw,'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',match);
const b = await legacy.previewWebLegacy(raw,'aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa',match);
assert.deepEqual(a,b);
assert.notEqual(a.records[0].recordId,a.records[1].recordId);
assert.equal(a.records[0].status,'ready');
assert.equal(a.records[2].status,'ambiguous');
assert.equal(a.records[0].sourceSha256.length,64);
assert.deepEqual(legacy.parseWebRounds('not json').records,[]);
assert.deepEqual(legacy.parseWebRounds('[{"players":[]}]').invalid,[0]);
console.log('Legacy web parser: distinct repeated rounds, stable IDs, matched/ambiguous review, malformed storage PASS');
